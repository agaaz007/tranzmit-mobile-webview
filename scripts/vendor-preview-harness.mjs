// Vendors the paywall preview harness into the config dashboard.
//
// The dashboard must measure the document the *app* renders, not the raw file.
// A raw browser render misses safe areas, the SDK wrapper CSS, localization,
// and the real usable height — which is the first rule in the harness's own
// RESPONSIVE_LEARNINGS. So the dashboard composes through the SDK's real
// `renderDocument()` and runs the same in-frame audit the authoring harness
// runs (`templates/preview/responsive.mjs` in tranzmit-react-native-sdk).
//
// Two files are vendored into packages/server/public/config-dashboard:
//   responsive.mjs      copied verbatim — one definition of the device matrix
//                       and the checks, shared with the authoring harness.
//   compose.bundle.js   esbuild bundle of renderDocument + resolveTheme.
//
// preview-harness.json records where they came from and their hashes;
// tests/preview-harness-vendoring.test.ts fails when a vendored file drifts
// from its recorded hash.
//
// Usage:
//   TRANZMIT_RN_SDK=/path/to/tranzmit-react-native-sdk node scripts/vendor-preview-harness.mjs
//   node scripts/vendor-preview-harness.mjs            (falls back to npm pack)

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "..");
const target = join(repoRoot, "packages", "server", "public", "config-dashboard");

// Pinned when falling back to the registry. Bump deliberately: the composer
// decides how every paywall is laid out, so changing it changes what passes.
const PUBLISHED_VERSION = "0.5.0";

function sha256(contents) {
  return createHash("sha256").update(contents).digest("hex");
}

/** Resolves an SDK checkout with a built dist, or unpacks one from npm. */
function resolveSdk() {
  const checkout = process.env.TRANZMIT_RN_SDK;
  if (checkout) {
    const root = resolve(checkout);
    const compose = join(root, "packages", "react-native", "dist", "renderer", "compose.js");
    if (!existsSync(compose)) {
      throw new Error(
        `TRANZMIT_RN_SDK=${root} has no built composer at ${compose}.\n` +
        "Run `npm run build` in the SDK checkout first."
      );
    }
    return {
      source: "checkout",
      root,
      reactNative: join(root, "packages", "react-native"),
      shared: join(root, "packages", "shared"),
      harness: join(root, "templates", "preview", "responsive.mjs"),
      version: JSON.parse(readFileSync(join(root, "packages", "react-native", "package.json"), "utf8")).version,
    };
  }

  const staging = mkdtempSync(join(tmpdir(), "tranzmit-sdk-"));
  for (const name of ["@tranzmit/react-native", "@tranzmit/shared"]) {
    execFileSync("npm", ["pack", `${name}@${PUBLISHED_VERSION}`, "--pack-destination", staging], { stdio: "inherit" });
  }
  throw new Error(
    `No TRANZMIT_RN_SDK set. Tarballs were fetched into ${staging}, but the published package does not ship\n` +
    "templates/preview/responsive.mjs, which the audit needs. Point TRANZMIT_RN_SDK at an SDK checkout."
  );
}

const sdk = resolveSdk();
mkdirSync(target, { recursive: true });

// 1. The audit script and device matrix, byte-for-byte.
if (!existsSync(sdk.harness)) throw new Error(`Harness not found: ${sdk.harness}`);
cpSync(sdk.harness, join(target, "responsive.mjs"));

// 2. The composer, bundled for the browser. compose.ts is deliberately free of
//    react-native imports so it runs unchanged in Node, in the app, and here.
const entry = join(mkdtempSync(join(tmpdir(), "tranzmit-compose-")), "entry.js");
writeFileSync(entry, [
  `export { renderDocument } from ${JSON.stringify(join(sdk.reactNative, "dist", "renderer", "compose.js"))};`,
  `export { resolveTheme } from ${JSON.stringify(join(sdk.reactNative, "dist", "theme.js"))};`,
  `export const SDK_VERSION = ${JSON.stringify(sdk.version)};`,
].join("\n"));

await build({
  entryPoints: [entry],
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2020",
  legalComments: "none",
  outfile: join(target, "compose.bundle.js"),
  alias: { "@tranzmit/shared": join(sdk.shared, "dist", "index.js") },
  banner: {
    js: [
      "// GENERATED by scripts/vendor-preview-harness.mjs — do not edit.",
      `// @tranzmit/react-native ${sdk.version} renderDocument + resolveTheme, bundled for the`,
      "// dashboard so Submit measures the document the app actually renders.",
    ].join("\n"),
  },
});
rmSync(dirname(entry), { recursive: true, force: true });

const manifest = {
  sdkVersion: sdk.version,
  source: sdk.source,
  generatedBy: "scripts/vendor-preview-harness.mjs",
  files: {
    "responsive.mjs": sha256(readFileSync(join(target, "responsive.mjs"))),
    "compose.bundle.js": sha256(readFileSync(join(target, "compose.bundle.js"))),
  },
};
writeFileSync(join(target, "preview-harness.json"), `${JSON.stringify(manifest, null, 2)}\n`);

console.log(`Vendored @tranzmit/react-native ${sdk.version} from ${sdk.source}`);
for (const [file, hash] of Object.entries(manifest.files)) {
  console.log(`  ${file}  ${hash.slice(0, 16)}`);
}
